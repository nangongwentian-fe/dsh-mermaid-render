#!/usr/bin/env node
/**
 * Build the runtime halves of the `@local/mermaid-render` bundle.
 *
 * Inputs:
 *   vendor/mermaid.iife.min.js   pinned mermaid build (self-contained IIFE that
 *                                assigns `globalThis.__MERMAID__`)
 *   src/client.js                the authored enhancer (plain classic script)
 *
 * Outputs (both committed next to this package so a local link install needs no
 * build step):
 *   client.js                    the package's `./client` browser half
 *   client.mermaid.js            the package-local lazy chunk loaded through
 *                                require.async only when a diagram appears
 */
import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const vendorPath = join(root, 'vendor', 'mermaid.iife.min.js');
const vendor = readFileSync(vendorPath, 'utf8');

if (!vendor.includes('globalThis.__MERMAID__')) {
  throw new Error(`${vendorPath} does not assign globalThis.__MERMAID__; rebuild the pinned mermaid IIFE`);
}
if (/\bimport\s*\(/u.test(vendor)) {
  throw new Error(`${vendorPath} contains a dynamic import; the chunk must be self-contained`);
}

const header = `/**
 * Lazy mermaid chunk for @local/mermaid-render.
 *
 * Generated by scripts/build-client.mjs from vendor/mermaid.iife.min.js — do not
 * edit by hand. The factory materializes on first use and returns the pinned
 * mermaid API object; the module system fetches this script on demand through
 * require.async('./client.mermaid.js').
 */
window.__ModuleLoader__.load({
  id: '@local/mermaid-render',
  chunk: 'client.mermaid.js',
  factory() {
`;
const footer = `
    return globalThis.__MERMAID__;
  },
});
`;
writeFileSync(join(root, 'client.mermaid.js'), `${header}${vendor}\n${footer}`);

const source = readFileSync(join(root, 'src', 'client.js'), 'utf8');
writeFileSync(join(root, 'client.js'), source);

for (const name of ['client.js', 'client.mermaid.js']) {
  const size = statSync(join(root, name)).size;
  console.log(`${name}: ${(size / 1024).toFixed(1)} KiB`);
}
